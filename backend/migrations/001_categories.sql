-- BEGIN открывает SQL-транзакцию.
-- Если при выполнении возникнет ошибка,
-- изменения можно отменить через ROLLBACK.
BEGIN;


-- =====================================================
-- 1. СОЗДАЁМ ТАБЛИЦУ КАТЕГОРИЙ
-- =====================================================

CREATE TABLE categories (

    -- PostgreSQL автоматически выдаёт ID.
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    -- Название категории.
    name TEXT NOT NULL,

    -- Доход или расход.
    type TEXT NOT NULL
        CHECK (type IN ('income', 'expense')),

    -- Запрещаем пустые названия.
    CONSTRAINT categories_name_not_empty
        CHECK (length(trim(name)) > 0),

    -- Требуем нижний регистр и отсутствие
    -- пробелов по краям.
    CONSTRAINT categories_name_normalized
        CHECK (name = lower(trim(name))),

    -- Одинаковые названия одного типа запрещены.
    CONSTRAINT categories_name_type_unique
        UNIQUE (name, type)
);


-- =====================================================
-- 2. УДАЛЯЕМ СТАРЫЕ ТЕСТОВЫЕ ТРАНЗАКЦИИ
-- =====================================================

-- ВНИМАНИЕ: удаляет все строки transactions.
DELETE FROM transactions;


-- =====================================================
-- 3. ДОБАВЛЯЕМ ВНЕШНИЙ КЛЮЧ
-- =====================================================

-- category_id хранит ID записи из categories.
-- REFERENCES гарантирует существование категории.
ALTER TABLE transactions
ADD COLUMN category_id BIGINT NOT NULL
REFERENCES categories(id);


-- =====================================================
-- 4. УДАЛЯЕМ СТАРЫЙ ТЕКСТОВЫЙ СТОЛБЕЦ
-- =====================================================

ALTER TABLE transactions
DROP COLUMN category;


-- =====================================================
-- 5. ПОДТВЕРЖДАЕМ ИЗМЕНЕНИЯ
-- =====================================================

COMMIT;
